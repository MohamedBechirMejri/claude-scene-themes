/**
 * Embeds the JPEGs in `assets/` into `hooks/scenes/assets.ts` as data URIs.
 *
 * A scene's SVG loads nothing from outside itself, so its pictures travel
 * inside the markup. Run after changing an asset:
 *
 *   bun scripts/embed-assets.ts
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const root = join(import.meta.dir, '..')
const assetsDir = join(root, 'assets')
const target = join(root, 'hooks', 'scenes', 'assets.ts')

/** `plate-abyss.jpg` → `ABYSS_PLATE`, `sprite-disk.jpg` → `DISK_SPRITE`. */
function exportName(file: string): string {
  const [kind = '', ...rest] = file.replace(/\.jpg$/, '').split('-')

  return [...rest, kind].join('_').toUpperCase()
}

const files = readdirSync(assetsDir).filter(file => file.endsWith('.jpg')).sort()
const lines = files.map(file => {
  const base64 = readFileSync(join(assetsDir, file)).toString('base64')

  return `export const ${exportName(file)} = 'data:image/jpeg;base64,${base64}'`
})

writeFileSync(
  target,
  `// Generated by scripts/embed-assets.ts from assets/*.jpg. Don't edit by hand.\n\n${lines.join('\n\n')}\n`,
)
console.log(`Wrote ${files.length} assets to ${target}`)
